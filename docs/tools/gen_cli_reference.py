"""Generate docs/reference/cli.md from the real command tree (Typer -> Click).

    uv run python docs/tools/gen_cli_reference.py          # rewrite docs/reference/cli.md
    uv run python docs/tools/gen_cli_reference.py --check  # exit 1 if it is out of date

tests/unit/test_docs.py runs the check, so a CLI change that is not reflected in the
reference fails the test suite. Hand-written explanation belongs in the guides; this
page is only what the implementation declares.
"""

from __future__ import annotations

import sys
from pathlib import Path

import typer.main

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs/reference/cli.md"

HEADER = """# CLI reference

<!-- Generated by docs/tools/gen_cli_reference.py from the Typer application in
src/brandsentinel/cli.py. Do not edit by hand: run the generator. -->

Generated from the command definitions in
[`src/brandsentinel/cli.py`](../../src/brandsentinel/cli.py). For what the commands are for and
which ones are safe where, see [Getting started](../guide/getting-started.md) and
[Reproducibility](../guide/reproducibility.md).

Every command accepts the global option `-c/--config PATH` (before the command name):
the configuration file. Without it, `$BRANDSENTINEL_CONFIG` is used, then the built-in
defaults (which put the data directory at `./data`). `$BRANDSENTINEL_DATA_DIR` overrides
`data_dir` from either source. Commands that open a store act on the configured
`data_dir`, and refuse to run as root or with none of those three (a guard not yet
installed in production, which does not check for the service account), so always pass
an explicit `-c` outside a scratch checkout.

**Commands that open a store write to it, including inspection commands** such as
`status` and `cases list`. They create a missing store, apply migrations and sweep
orphan blobs ([Storage](../concepts/storage.md)). **Only `run` and `registry collect`
check the account**. The other store-opening commands accept any non-root account, and
commands that do not open a store still run as root
([Security model](../concepts/security.md#which-commands-enforce-it)). Production use is
owner-operated, as the service account
([Deployment](../operations/deployment.md#production-cli-operations)).
"""


def command_tree():
    from brandsentinel.cli import app

    return typer.main.get_command(app)


# Typer vendors Click privately; the objects are read by duck typing only.
def _is_group(cmd) -> bool:
    return hasattr(cmd, "commands")


def _help(cmd) -> str:
    text = (cmd.help or "").strip()
    return " ".join(text.split("\n\n")[0].split())


def _param_rows(cmd) -> list[str]:
    rows = []
    for p in cmd.params:
        if p.param_type_name == "argument":
            name = f"`{p.human_readable_name.upper()}`" + ("..." if p.nargs == -1 else "")
            kind = "argument" + ("" if p.required else ", optional")
            rows.append(f"| {name} | {kind} | {' '.join((getattr(p, 'help', '') or '').split())} |")
        elif p.param_type_name == "option":
            if p.name == "help":
                continue
            names = " / ".join(f"`{o}`" for o in [*p.opts, *p.secondary_opts])
            flag = p.is_flag or getattr(p, "count", False)
            kind = "flag" if flag else f"option ({p.type.name})"
            default = p.default
            if default not in (None, False, (), []) and not callable(default) and not p.is_flag:
                kind += f", default `{default}`"
            rows.append(f"| {names} | {kind} | {' '.join((p.help or '').split())} |")
    return rows


def _walk(cmd, path: list[str], out: list[str]) -> None:
    if _is_group(cmd):
        for name in sorted(cmd.commands):
            sub = cmd.commands[name]
            if sub.hidden:
                continue
            _walk(sub, [*path, name], out)
        return
    full = " ".join(path)
    out.append(f"\n## `brandsentinel {full}`\n")
    out.append(_help(cmd) + "\n")
    rows = _param_rows(cmd)
    if rows:
        out.append("| Parameter | Kind | Description |\n|---|---|---|")
        out.extend(rows)
        out.append("")


def render() -> str:
    root = command_tree()
    out = [HEADER]
    out.append("\n## Commands\n")
    out.append("| Command | Summary |\n|---|---|")
    for name in sorted(root.commands):
        cmd = root.commands[name]
        if cmd.hidden:
            continue
        if _is_group(cmd):
            for sub in sorted(cmd.commands):
                out.append(f"| `{name} {sub}` | {_help(cmd.commands[sub])} |")
        else:
            out.append(f"| `{name}` | {_help(cmd)} |")
    _walk(root, [], out)
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if argv == ["--check"]:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run docs/tools/gen_cli_reference.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
